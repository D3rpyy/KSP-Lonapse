#!/usr/bin/env python3
"""Generate the bundled Mandarin character readings from Unicode 17.0.0 Unihan.

Download https://www.unicode.org/Public/17.0.0/ucd/Unihan.zip, then run
python3 tools/build_chinese_pronunciation.py /path/to/Unihan.zip
The generated data retains the Unicode License v3, see LICENSE-UNICODE.
"""

import argparse
import collections
import hashlib
from pathlib import Path
import unicodedata
import zipfile


SHA256 = "f7a48b2b545acfaa77b2d607ae28747404ce02baefee16396c5d2d7a8ef34b5e"
REPO = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("unihan", type=Path)
    args = parser.parse_args()
    if hashlib.sha256(args.unihan.read_bytes()).hexdigest() != SHA256:
        parser.error("expected the Unicode 17.0.0 Unihan.zip (SHA256 mismatch)")
    with zipfile.ZipFile(args.unihan) as archive:
        readings = archive.read("Unihan_Readings.txt").decode("utf-8")
    groups = collections.defaultdict(list)
    for line in readings.splitlines():
        if "\tkMandarin\t" not in line:
            continue
        code, _, reading = line.split("\t")
        # First reading is the preferred mainland Mandarin reading. Strip tones.
        pinyin = "".join(c for c in unicodedata.normalize("NFD", reading.split()[0])
                         if not unicodedata.combining(c)).lower()
        if not pinyin.isascii() or not pinyin.isalpha():
            raise ValueError("unexpected reading " + reading)
        groups[pinyin].append(int(code[2:], 16))
    lines = [
        "// Generated by tools/build_chinese_pronunciation.py. Do not edit by hand.",
        "// Unicode 17.0.0 Unihan kMandarin, preferred reading with tones removed.",
        "// Copyright © 2025 Unicode, Inc. Distributed under Unicode License v3.",
        "// See LICENSE-UNICODE and the shipped LICENSE-UNICODE.txt.",
        "// Source https://www.unicode.org/Public/17.0.0/ucd/Unihan.zip",
        "using System.Collections.Generic;",
        "",
        "namespace Lonapse",
        "{",
        "    static partial class ChinesePronunciation",
        "    {",
        "        static Dictionary<int, string> BuildReadings()",
        "        {",
        "            var readings = new Dictionary<int, string>(44349);",
    ]
    for pinyin, codes in sorted(groups.items()):
        chars = "".join("\\u%04X" % cp if cp <= 0xFFFF else "\\U%08X" % cp
                        for cp in sorted(codes))
        lines.append('            Add(readings, "%s", "%s");' % (pinyin, chars))
    lines += [
        '            readings[0x3007] = "ling"; // Ideographic zero.',
        "            return readings;",
        "        }",
        "    }",
        "}",
    ]
    target = REPO / "src" / "ChinesePronunciation.Data.cs"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Generated %d character readings in %s" % (sum(map(len, groups.values())) + 1, target))


if __name__ == "__main__":
    main()
